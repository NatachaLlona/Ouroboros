"""Export fixed public query metadata from the implemented schemas, without a database."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.schemas.catalogue import RESOURCES, PATTERN_HELP


def render():
    result = {}
    for name in ('platforms', 'tags', 'work_classifications'):
        resource = RESOURCES[name]
        properties = resource.query.model_json_schema()['properties']
        filters = []
        for key, field in resource.query.model_fields.items():
            if key in ('display_timezone', 'page', 'page_size', 'order_by', 'order_direction'):
                continue
            schema = properties[key]
            alternatives = schema.get('anyOf', [schema])
            alternatives = [item for item in alternatives if item.get('type') != 'null']
            choices = next((item['enum'] for item in alternatives if 'enum' in item), [])
            kind = ('boolean' if any(item.get('type') == 'boolean' for item in alternatives)
                    else 'date' if key.endswith('_date')
                    else 'integer' if key == 'tier' or key.startswith('sequence_')
                    else 'decimal' if key == 'price_amount' else 'text')
            filters.append({'key': key, 'kind': kind, 'choices': choices, 'pattern': field.description == PATTERN_HELP})
        result[name] = {'filters': filters, 'orderBy': properties['order_by']['enum'], 'defaultOrder': properties['order_by']['default']}
    return '// Generated by scripts/sync_frontend_contracts.py; do not edit.\nexport const publicContracts = ' + json.dumps(result, ensure_ascii=False, indent=2) + ' as const;\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'frontend/src/app/catalogue/contracts.generated.ts'
    expected = render()
    if args.check:
        if not path.is_file() or path.read_text(encoding='utf-8') != expected:
            raise SystemExit('Frontend public query metadata is stale; run scripts/sync_frontend_contracts.py')
    else:
        path.write_text(expected, encoding='utf-8')
    print('Frontend metadata matches the three implemented resource contracts')


if __name__ == '__main__':
    main()
