"""Maintain explicit, opt-in array creation examples using public placeholders."""
GROUP = 'Atomic array creation (isolated opt-in only)'
GUARD = 'if (pm.variables.get("catalogue_destructive_opt_in") !== "isolated") { pm.execution.skipRequest(); }'


def augment(collection, request, examples):
    collection['item'] = [item for item in collection['item'] if item['name'] != GROUP]
    known = {variable['key'] for variable in collection['variable']}
    for name in ('batch_tag_first_id', 'batch_tag_second_id'):
        if name not in known:
            collection['variable'].append(dict(key=name, value='', type='string'))
    items = []
    check = ['pm.test("Ordered mutation result",()=>{ const r=pm.response.json(); pm.expect(r.created_count).to.eql(2); pm.expect(r.items).to.have.length(2); pm.expect(r).not.to.have.property("page"); });']
    for table, first in {**examples, 'test': {'value': 'First array item'}}.items():
        second = dict(first)
        for key in ('title', 'platform_name', 'display_name_tags', 'display_name_tag_categories', 'observations', 'value'):
            if key in second:
                second[key] = 'Second array item'
        for key in ('tag_name', 'tag_category_name', 'work_classification_name'):
            if key in second:
                second[key] += '_second'
        body = [dict(first), second]
        if table == 'tag_category_relationships':
            body[0]['id_tags'], body[1]['id_tags'] = '{{batch_tag_first_id}}', '{{batch_tag_second_id}}'
        item = request('BATCH ' + table + ' - Create array (opt-in)', 'POST', '/' + table, 201,
                       token='standard_token' if table == 'test' else 'supervisor_token', body=body, scripts=check)
        if table == 'tags':
            item['event'][0]['script']['exec'] += [
                'pm.collectionVariables.set("batch_tag_first_id",pm.response.json().items[0].id_tags);',
                'pm.collectionVariables.set("batch_tag_second_id",pm.response.json().items[1].id_tags);']
        items.append(item)
    items.append(request('BATCH test - One-item array (opt-in)', 'POST', '/test', 201, token='standard_token',
        body=[{'value': 'One array item'}], scripts=['pm.test("One item is still a batch",()=>pm.expect(pm.response.json().created_count).to.eql(1));']))
    three_hundred = request('BATCH test - Create 300 (opt-in)', 'POST', '/test', 201, token='standard_token',
        body=[{'value': 'Generated by the pre-request script'}], scripts=[
            'pm.test("300 ordered records",()=>{ const r=pm.response.json(); pm.expect(r.created_count).to.eql(300); r.items.forEach((x,i)=>pm.expect(x.value).to.eql("Batch item " + i)); });'])
    three_hundred['event'].insert(0, dict(listen='prerequest', script=dict(type='text/javascript', exec=[
        'pm.request.body.update(JSON.stringify(Array.from({length:300},(_,i)=>({value:"Batch item " + i}))));'])))
    items.append(three_hundred)
    items.append(request('BATCH classifications - Sequential tiers (opt-in)', 'POST', '/work_classifications', 201,
        token='supervisor_token', body=[
            {'work_classification_name':'batch_append','display_name_work_classifications':'Append'},
            {'work_classification_name':'batch_first','display_name_work_classifications':'Insert first','tier':1},
            {'work_classification_name':'batch_second','display_name_work_classifications':'Insert second','tier':2}],
        scripts=['pm.test("Sequential final tiers",()=>{ const r=pm.response.json(); pm.expect(r.created_count).to.eql(3); pm.expect(r.items[1].tier).to.eql(1); pm.expect(r.items[2].tier).to.eql(2); });']))
    for item in items:
        item['event'].insert(0, dict(listen='prerequest',script=dict(type='text/javascript',exec=[GUARD])))
        item['request']['description'] += ' Atomic same-resource array; no page envelope. Zero-based error item indexes. Default maximum 300; api.max_batch_size and api.max_creation_body_bytes apply. Skipped unless explicitly opted into owned disposable QA. Referenced IDs must already exist; no implicit intra-array references.'
    items.extend([
        request('BATCH - Empty array rejected','POST','/test',422,token='standard_token',body=[]),
        request('BATCH - Nested array rejected','POST','/test',422,token='standard_token',body=[[{'value':'Invalid'}]]),
        request('BATCH - Non-object rejected','POST','/test',422,token='standard_token',body=[{'value':'Valid'},None]),
        request('BATCH - Indexed validation rollback','POST','/test',422,token='standard_token',body=[{'value':'Must roll back'},{'value':None}],scripts=[
            'pm.test("Zero-based failing item",()=>pm.expect(pm.response.json().error.details.some(d=>d.loc[0]==="body" && d.loc[1]===1)).to.eql(true));']),
        request('BATCH - Standard catalogue denied','POST','/works',403,token='standard_token',body=[{'title':'Denied','title_language':'en'}]),
        request('BATCH - Inspect captured interaction','GET','/api_audit_logs',200,token='supervisor_token',
            params=[dict(key='interaction_id',value='{{audit_interaction_id}}')]),
    ])
    oversized = request('BATCH - Oversized array rejected', 'POST', '/test', 422, token='standard_token',
        body=[{'value': 'Generated 301 items by pre-request script'}])
    oversized['event'].insert(0, dict(listen='prerequest', script=dict(type='text/javascript', exec=[
        GUARD, 'pm.request.body.update(JSON.stringify(Array.from({length:301},()=>({value:"Oversized example"}))));'])))
    oversized['request']['description'] += ' Requires default api.max_batch_size=300 and explicit isolated opt-in; a larger configured limit can accept this body.'
    items.append(oversized)
    collection['item'].append(dict(name=GROUP,description='Use fresh owned QA data and pre-existing captured catalogue IDs. Creates are explicit isolated opt-in; array POST uses normal creation permissions, independently of administrator bulk PUT/DELETE. Inspect each response interaction before running another request.',item=items))
