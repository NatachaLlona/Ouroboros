"""Load the single QA catalogue and render its generated manual test plan."""
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "qa/scenarios.json"


def load_catalog(root=ROOT):
    """Read public scenario metadata; never read runtime configuration/secrets."""
    return json.loads((root/"qa/scenarios.json").read_text(encoding="utf-8"))


def test_inventory(root=ROOT):
    """Discover stable unittest selectors statically without executing tests."""
    result = set()
    for file in (root/"tests").glob("test_*.py"):
        tree = ast.parse(file.read_text(encoding="utf-8"))
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                for method in node.body:
                    if isinstance(method, (ast.FunctionDef, ast.AsyncFunctionDef)) and method.name.startswith("test_"):
                        result.add(f"{file.stem}.{node.name}.{method.name}")
    return result


def validate_catalog(catalog, root=ROOT):
    """Reject missing selectors, duplicate identities and divergent QA documentation.

    Returns:
        A list of public consistency errors, empty only when checks pass.
    """
    errors, ids, names, mapped = [], set(), set(), set()
    for scenario in catalog["scenarios"]:
        for key in ("id", "name", "objective", "prerequisites", "actor", "steps", "expected", "tests", "type", "requests", "log_evidence"):
            if key not in scenario: errors.append("Missing catalogue field: "+key)
        if scenario["id"] in ids or scenario["name"] in names:
            errors.append("Duplicate scenario identity")
        ids.add(scenario["id"])
        names.add(scenario["name"])
        if scenario["type"] not in ("automated", "manual", "both"):
            errors.append("Invalid scenario type")
        if scenario["type"] != "manual" and not scenario["tests"]:
            errors.append("Automated scenario has no test selectors")
        if scenario["type"] == "manual" and scenario["tests"]:
            errors.append("Visual/manual scenario must not imply HTTP automation")
        mapped.update(scenario["tests"])
    inventory = test_inventory(root)
    errors.extend("Missing test selector: "+item for item in sorted(mapped-inventory))
    errors.extend("Unmapped automated test: "+item for item in sorted(inventory-mapped))
    for scenario in catalog["scenarios"]:
        if any(value not in ids for value in scenario.get("depends_on", [])):
            errors.append("Unknown scenario dependency")
    return errors


def render_plan(catalog, root=ROOT):
    """Generate identical IDs/names/manual cases directly from the catalogue."""
    lines = ["<!-- Generated by scripts/generate_qa_docs.py. Edit qa/scenarios.json or docs/QA_SETUP.md. -->",
             "# 🧪 **Ouroboros QA test plan**", "", (root/"docs/QA_SETUP.md").read_text(encoding="utf-8").strip(),
             "", "## 🗂️ **Scenario index**", "", "| ID | Scenario | Verification type |", "| --- | --- | --- |"]
    for item in catalog["scenarios"]:
        lines.append(f'| {item["id"]} | [{item["name"]}](#scenario-{item["id"].replace(".", "-")}) | {item["type"]} |')
    for item in catalog["scenarios"]:
        lines += ["", f'<a id="scenario-{item["id"].replace(".", "-")}"></a>',
                  f'## {item["id"]} - {item["name"]}', "", f'**Objective:** {item["objective"]}', "",
                  f'**User:** {item["actor"]}', "", '**Prerequisites and data:** '+"; ".join(item["prerequisites"]), "",
                  f'**Type:** {item["type"]}. Automated PASS describes only the mapped checks; visual/manual execution requires separate QA evidence.', "",
                  "**Exact manual actions:**", ""]
        lines.extend(f"{i}. {step}" for i, step in enumerate(item["steps"], 1))
        if item["requests"]:
            lines += ["", "**HTTP contract:**", "", "| Method / endpoint | Parameters / headers | Body | Expected / capture |", "| --- | --- | --- | --- |"]
            for req in item["requests"]:
                def cell(value): return str(value).replace("<", "&lt;").replace(">", "&gt;").replace("|", "&#124;").replace("\n", "<br>")
                lines.append(f'| {cell(req["method"])} `{cell(req["endpoint"])}` | {cell(req["parameters_headers"])} | {cell(req["body"])} | {cell(req["expected"])} |')
        lines += ["", "**Approval criterion:** "+item["expected"], ""]
        evidence = item["log_evidence"]
        lines += ["", "**Exact log evidence:**", "", evidence["locate"], "",
                  "| Level / visibility | Category | Method / endpoint | Exact message / presence | Context fields / values |",
                  "| --- | --- | --- | --- | --- |"]
        for rule in evidence["events"]:
            context = ", ".join(rule["context_fields"])
            if rule.get("context_values"): context += "; "+json.dumps(rule["context_values"],ensure_ascii=False)
            visibility = " (absent at INFO)" if rule["level"] == "DEBUG" else ""
            conditions = "" if not rule.get("statuses") else " for HTTP "+str(rule["statuses"])
            target = rule["method"]+" "+rule["endpoint"] if rule["category"] == "request" else "None (application event)"
            lines.append(f'| {rule["level"]}{visibility} | {rule["category"]} | {target} | `{rule["message"]}` — **{rule["presence"]}**{conditions} | {context or "empty object"} |')
        lines += ["", "**Forbidden evidence data:** "+"; ".join(evidence["forbidden_data"]), "",
                  "**Automated correspondence:**", ""]
        lines.extend("- `"+test+"`" for test in item["tests"])
        if not item["tests"]: lines.append("- **None:** record manual evidence; never infer PASS from documentation.")
        lines += ["", "| QA result (not run / PASS / FAIL / BLOCKED) | Evidence (sanitized) | Notes / tester / date |",
                  "| --- | --- | --- |", "| Not run | | |"]
    return "\n".join(lines)+"\n"
