class StateTests(unittest.TestCase):
    def test_protected_atomic_write_and_reserved_names(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            admin.remember(root, 'initial_master')
            self.assertEqual(admin.previous_master(root, [], 'different'), 'initial_master')
            with self.assertRaises(ConfigurationError):
                admin.remember(root, 'different')
        for value in ('ouroboros_api_login','ouroboros_owner','ouroboros_runtime','bad;sql'):
            with self.assertRaises(ConfigurationError):
                admin.role_name(value)

    def test_unattended_change_never_prompts_or_connects(self):
        with tempfile.TemporaryDirectory() as directory:
            root=Path(directory)
            resources=[{'Config':{'Env':['POSTGRES_USER=old_master']}}]
            with patch('sys.stdin.isatty',return_value=False),patch.object(admin,'connection') as connect,patch.object(admin,'read_password') as password:
                with self.assertRaisesRegex(ConfigurationError,'interactive'):
                    admin.ensure(root, {}, {'master_user':'new_master'}, resources)
                connect.assert_not_called()
                password.assert_not_called()


class MasterHandoverTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.harness=test_postgres.PostgreSQLTests
        cls.harness.setUpClass()

    @classmethod
    def tearDownClass(cls):
        cls.harness.tearDownClass()

    def setUp(self):
        self.root=self.harness.fixture
        self.document=self.harness.document
        self.operational=dict(self.harness.operational)
        self.old=self.operational['master_user']
        self.new='master_'+secrets.token_hex(5)
        self.password='New1!'+secrets.token_hex(4)
        self.resources=[{'Config':{'Env':['POSTGRES_USER='+self.old]}}]

    def connect(self,name=None,password=None):
        return admin.connection(self.document,self.operational,name or self.old,password or self.harness.password)

    def handover(self,answers=None):
        self.operational['master_user']=self.new
        with patch('sys.stdin.isatty',return_value=True),patch.object(admin,'read_password',return_value=self.harness.password),patch.object(admin,'prompt_password',return_value=self.password),patch('builtins.input',side_effect=answers or ['CREATE '+self.new,'']),contextlib.redirect_stdout(io.StringIO()):
            admin.ensure(self.root,self.document,self.operational,self.resources)

    def tearDown(self):
        # Remove only exact role names generated by this test, never normal roles.
        with self.connect() as connection:
            for name in (self.new, getattr(self,'second',self.new)):
                connection.execute(sql.SQL('DROP ROLE IF EXISTS {}').format(sql.Identifier(name)))
        admin.atomic_write(self.root/self.operational['secret_file'],self.harness.password)
        admin.state_write(self.root/admin.IDENTITY,{'master_user':self.old})
        for relative in (admin.JOURNAL,admin.PENDING):
            (self.root/relative).unlink(missing_ok=True)

    def test_create_verify_and_restart_without_reenrollment(self):
        with self.connect() as connection:
            before=connection.execute(render('SELECT version,checksum FROM {foundation_migration} ORDER BY version',self.document)).fetchall()
            person=connection.execute(render('SELECT id_super_administrator,id_app_user,id_api_user FROM {super_administrator}',self.document)).fetchall()
        self.handover()
        with self.connect(self.new,self.password) as connection:
            self.assertEqual(connection.execute('SELECT rolsuper,pg_has_role(current_user,\'ouroboros_owner\',\'MEMBER\') FROM pg_roles WHERE rolname=current_user').fetchone(),(True,True))
            self.assertEqual(connection.execute(render('SELECT version,checksum FROM {foundation_migration} ORDER BY version',self.document)).fetchall(),before)
            self.assertEqual(connection.execute(render('SELECT id_super_administrator,id_app_user,id_api_user FROM {super_administrator}',self.document)).fetchall(),person)
            self.assertEqual(connection.execute(render("SELECT count(*) FROM {api_audit_log} WHERE resource='sql_master' AND target_id=%s",self.document),(self.new,)).fetchone()[0],1)
        with patch.object(runtime,'PROJECT',self.harness.project),patch.object(runtime,'prepare_initial',return_value=(self.document,self.operational)),patch('builtins.input',side_effect=AssertionError('Unexpected enrollment')),patch.object(admin,'read_password',side_effect=AssertionError('Unexpected password')):
            self.assertEqual(runtime.main(self.root,['--database-only']),0)

    def test_runtime_detects_config_change_and_preserves_saas_credentials(self):
        with self.connect() as connection:
            credentials=connection.execute(render('SELECT id_api_user_credential,secret_hash FROM {api_user_credential} ORDER BY id_api_user_credential',self.document)).fetchall()
        self.operational['master_user']=self.new
        with patch.object(runtime,'PROJECT',self.harness.project),patch.object(runtime,'prepare_initial',return_value=(self.document,self.operational)),patch('sys.stdin.isatty',return_value=True),patch.object(admin,'read_password',return_value=self.harness.password),patch.object(admin,'prompt_password',return_value=self.password),patch('builtins.input',side_effect=['CREATE '+self.new,'']):
            self.assertEqual(runtime.main(self.root,['--database-only']),0)
        with self.connect(self.new,self.password) as connection:
            after=connection.execute(render('SELECT id_api_user_credential,secret_hash FROM {api_user_credential} ORDER BY id_api_user_credential',self.document)).fetchall()
            self.assertTrue(credentials==after,'SaaS credential IDs and hashes must remain unchanged')

    def test_cancel_and_dependency_failure_do_not_delete_records(self):
        self.operational['master_user']=self.new
        with self.assertRaisesRegex(ConfigurationError,'cancelled'):
            self.handover(['not confirmed'])
        with self.connect() as connection:
            self.assertIsNone(connection.execute('SELECT 1 FROM pg_roles WHERE rolname=%s',(self.new,)).fetchone())
        self.handover()
        with self.connect() as connection:
            connection.execute('CREATE SCHEMA dependency_fixture')
            try:
                connection.execute(sql.SQL('CREATE TABLE dependency_fixture.kept(value integer); ALTER TABLE dependency_fixture.kept OWNER TO {}').format(sql.Identifier(self.new)))
                with patch('builtins.input',return_value='DELETE '+self.new),contextlib.redirect_stdout(io.StringIO()):
                    with self.assertRaisesRegex(ConfigurationError,'dependencies'):
                        admin.retire(connection,self.document,self.new)
                self.assertIsNotNone(connection.execute("SELECT to_regclass('dependency_fixture.kept')").fetchone()[0])
            finally:
                connection.execute('DROP TABLE dependency_fixture.kept')
                connection.execute('DROP SCHEMA dependency_fixture')

    def test_wrong_current_password_and_existing_role_are_preserved(self):
        self.operational['master_user']=self.new
        with patch('sys.stdin.isatty',return_value=True),patch.object(admin,'read_password',return_value='Wrong1!password'),patch.object(admin,'prompt_password') as prompt,contextlib.redirect_stdout(io.StringIO()):
            with self.assertRaisesRegex(ConfigurationError,'transition failed'):
                admin.ensure(self.root,self.document,self.operational,self.resources)
            prompt.assert_not_called()
        self.handover()
        # An existing target with no journal is never adopted or reset.
        admin.state_write(self.root/admin.IDENTITY,{'master_user':self.old})
        with self.assertRaisesRegex(ConfigurationError,'already exists'):
            self.handover()
        with self.connect(self.new,self.password) as connection:
            admin.verify(connection,self.document)

    def test_sql_and_audit_rollback_together(self):
        with patch.object(admin,'evidence',side_effect=RuntimeError('Synthetic audit failure')):
            with self.assertRaises(RuntimeError):
                self.handover()
        with self.connect() as connection:
            self.assertIsNone(connection.execute('SELECT 1 FROM pg_roles WHERE rolname=%s',(self.new,)).fetchone())

    def test_file_failure_after_commit_is_resumable(self):
        write=admin.atomic_write
        def failing(path,value):
            if path==self.root/self.operational['secret_file']:
                raise OSError('Synthetic publication failure')
            return write(path,value)
        with patch.object(admin,'atomic_write',side_effect=failing):
            with self.assertRaises(OSError):
                self.handover()
        self.assertTrue((self.root/admin.JOURNAL).exists())
        with patch('sys.stdin.isatty',return_value=True),patch.object(admin,'read_password',side_effect=AssertionError('Old password not needed for journal recovery')),patch.object(admin,'prompt_password',side_effect=AssertionError('No reset')),patch('builtins.input',return_value=''),contextlib.redirect_stdout(io.StringIO()):
            admin.ensure(self.root,self.document,self.operational,self.resources)
        self.assertFalse((self.root/admin.JOURNAL).exists())
        with self.connect(self.new,self.password) as connection:
            admin.verify(connection,self.document)

    def test_decline_and_confirm_delete_ordinary_previous_master(self):
        self.handover()
        self.second='master_'+secrets.token_hex(5)
        with self.connect(self.new,self.password) as connection:
            admin.create(connection,self.document,self.second,'Next1!'+secrets.token_hex(4))
        with self.connect() as connection:
            with patch('builtins.input',return_value=''),contextlib.redirect_stdout(io.StringIO()):
                admin.retire(connection,self.document,self.new)
            self.assertIsNotNone(connection.execute('SELECT 1 FROM pg_roles WHERE rolname=%s',(self.new,)).fetchone())
            with patch('builtins.input',return_value='DELETE '+self.new),contextlib.redirect_stdout(io.StringIO()):
                admin.retire(connection,self.document,self.new)
            self.assertIsNone(connection.execute('SELECT 1 FROM pg_roles WHERE rolname=%s',(self.new,)).fetchone())

    def test_pinned_initial_master_can_be_disabled_without_data_deletion(self):
        self.handover()
        with self.connect(self.new,self.password) as connection:
            try:
                with patch('builtins.input',return_value='DISABLE '+self.old),contextlib.redirect_stdout(io.StringIO()):
                    admin.retire(connection,self.document,self.old)
                self.assertEqual(connection.execute('SELECT rolcanlogin FROM pg_roles WHERE rolname=%s',(self.old,)).fetchone(),(False,))
                with self.assertRaises(psycopg.Error):
                    self.connect()
            finally:
                # Restore only the disposable cluster's original administrative LOGIN.
                with connection.transaction():
                    admin.quiet(connection)
                    verifier=connection.pgconn.encrypt_password(self.harness.password.encode(),self.old.encode(),b'scram-sha-256').decode()
                    connection.execute(sql.SQL('ALTER ROLE {} LOGIN PASSWORD {}').format(sql.Identifier(self.old),sql.Literal(verifier)))


